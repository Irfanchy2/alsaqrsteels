// Generates supabase/seed/content.sql from src/lib/content/seed.ts.
// Run: NEXT_PUBLIC_MEDIA_BASE=<supabase>/storage/v1/object/public/media npx tsx scripts/seed-sql.ts
import { writeFileSync, mkdirSync } from "node:fs";
import {
  company,
  services,
  projects,
  faqs,
  highlights,
  processSteps,
  WORK_PHOTOS,
} from "../src/lib/content/seed";

const q = (v: string | null | undefined) =>
  v === null || v === undefined ? "null" : `'${v.replace(/'/g, "''")}'`;
const arr = (v: string[]) => `array[${v.map(q).join(", ")}]::text[]`;
const num = (v: number | null | undefined) => (v === null || v === undefined ? "null" : String(v));

const out: string[] = [];
out.push("-- Generated by scripts/seed-sql.ts — do not edit by hand.");
out.push("begin;");

out.push(`update public.site_settings set
  company_name = ${q(company.name)},
  tagline = ${q(company.tagline)},
  hero_title = ${q(company.heroTitle)},
  hero_subtitle = ${q(company.heroSubtitle)},
  hero_image = ${q(WORK_PHOTOS.steelFrame.src)},
  logo_url = ${q(company.logoUrl)},
  about_title = ${q(company.aboutTitle)},
  about_body = ${q(company.aboutBody)},
  established_year = ${num(company.establishedYear)},
  address = ${q(company.address)},
  phone_1 = ${q(company.phones[0]?.display)},
  phone_2 = ${q(company.phones[1]?.display ?? null)},
  whatsapp = ${q(company.whatsapp)},
  email = ${q(company.email)},
  business_hours = ${q(company.hours)},
  facebook_url = ${q(company.facebookUrl)},
  instagram_url = ${q(company.instagramUrl)},
  maps_url = ${q(company.mapsUrl)},
  updated_at = now()
where id = 1;`);

out.push("delete from public.services;");
services.forEach((s, i) => {
  out.push(`insert into public.services
  (slug, number, title, summary, intro, body, bullets, applications, illustration,
   image_url, image_alt, image_width, image_height, seo_title, seo_description, sort_order, published)
values (${q(s.slug)}, ${q(s.number)}, ${q(s.title)}, ${q(s.summary)}, ${q(s.intro)}, null,
  ${arr(s.scope)}, ${arr(s.applications)}, ${q(s.illustration)},
  ${q(s.image?.src)}, ${q(s.image?.alt)}, ${num(s.image?.width)}, ${num(s.image?.height)},
  ${q(s.seoTitle)}, ${q(s.seoDescription)}, ${i + 1}, true);`);
});

// Legacy gallery rows from the WordPress import: images no longer exist.
out.push(
  "update public.projects set published = false, featured = false, category = 'legacy-gallery' where slug is null;"
);
projects.forEach((p, i) => {
  out.push(`insert into public.projects
  (slug, code, title, category, sector, location, emirate, year, scope, description, status,
   services, client_name, client_public, featured, published, sort_order)
values (${q(p.slug)}, ${q(p.code)}, ${q(p.title)}, 'projects', ${q(p.sector)}, ${q(p.location)},
  ${q(p.emirate)}, ${q(p.year)}, ${q(p.scope)}, ${q(p.description)}, ${q(p.status)},
  ${arr(p.services)}, null, false, ${p.featured}, true, ${i + 1})
on conflict (slug) do update set
  code = excluded.code, title = excluded.title, sector = excluded.sector,
  location = excluded.location, emirate = excluded.emirate, scope = excluded.scope,
  description = excluded.description, status = excluded.status, services = excluded.services,
  featured = excluded.featured, published = true, sort_order = excluded.sort_order;`);
});
// Recorded client for Taweelah (live site data) — kept private until documented.
out.push(
  "update public.projects set client_name = 'ADNOC Onshore', client_public = false where slug = 'taweelah-gas-compressor-station';"
);

out.push("delete from public.faqs;");
faqs.forEach((f, i) => {
  out.push(
    `insert into public.faqs (scope, question, answer, sort_order, published) values (${q(f.scope)}, ${q(f.question)}, ${q(f.answer)}, ${i + 1}, true);`
  );
});

out.push("delete from public.highlights;");
highlights.forEach((h, i) => {
  out.push(
    `insert into public.highlights (label, value, detail, sort_order, published) values (${q(h.label)}, ${q(h.value)}, ${q(h.detail)}, ${i + 1}, true);`
  );
});

out.push("delete from public.process_steps;");
processSteps.forEach((s, i) => {
  out.push(
    `insert into public.process_steps (title, body, sort_order, published) values (${q(s.title)}, ${q(s.body)}, ${i + 1}, true);`
  );
});

// Certifications found on the old site cannot be published (see docs/AUDIT.md).
out.push(`update public.certifications set published = false, verified = false,
  staff_note = 'Hidden in 2026 redesign: certificate image on the old site is issued to Capital Zone Inspection & Calibration Services and expired 03 Jun 2023. Upload a current certificate in the company name, then mark verified.'
  where title in ('ISO 9001', 'ISO 14001', 'ISO 45001');`);
out.push(`update public.certifications set title = 'In-Country Value (ICV) Certificate', standard = 'UAE National ICV Programme',
  certificate_number = '137849', holder_name = 'Al Saqr Alahmar Welding and Blacksmit - Sole Proprietorship L.L.C.',
  valid_until = '2026-01-24', issuer = 'Verified under ICV AUP by Mazars Chartered Accountants LLC',
  published = false, verified = false,
  staff_note = 'ICV certificate 137849 shows validity to 24 Jan 2026. Upload the renewed certificate, then mark verified.'
  where title = 'Registration';`);
out.push(`update public.certifications set published = false, verified = false,
  staff_note = 'Letter of appreciation: confirm permission to publish and upload the document.'
  where title = 'Letter of Appreciation';`);

// Client logos: hidden until the company confirms permission to display them.
out.push("update public.partners set published = false;");
// Testimonials: source not documented.
out.push("update public.testimonials set published = false;");

out.push("commit;");

mkdirSync("supabase/seed", { recursive: true });
writeFileSync("supabase/seed/content.sql", out.join("\n\n") + "\n");
console.log("wrote supabase/seed/content.sql");
